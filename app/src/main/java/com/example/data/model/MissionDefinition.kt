import androidx.compose.ui.graphics.Color

data class MissionDefinition(
    val id: String,
    val tier: Int,
    val nameAr: String,
    val subtitleAr: String,
    val briefingAr: String,
    val gravity: Float,              // m/s^2
    val atmosphericDensity: Float,   // kg/m^3 equivalent drag factor
    val baseWindSpeed: Float,        // m/s horizontal steady wind (+ right, - left)
    val windGustAmplitude: Float,    // m/s oscillating gust amplitude
    val dryMassKg: Float,
    val initialFuelKg: Float,
    val maxThrustNewtons: Float,
    val specificImpulseBurnRate: Float, // kg/s at 100% throttle
    val safeVerticalSpeed: Float,    // m/s max safe impact
    val safeHorizontalSpeed: Float,  // m/s max safe lateral drift
    val safeTiltDeg: Float,          // degrees max safe pitch
    val padWidthMeters: Float,       // landing pad width in world meters
    val startAltitudeMeters: Float,
    val startHorizontalOffset: Float,
    val startVelocityX: Float,
    val startVelocityY: Float,
    val skyTopColor: Color,
    val skyBottomColor: Color,
    val terrainTopColor: Color,
    val terrainDeepColor: Color,
    val accentColor: Color,
    val seed: Long,
)

